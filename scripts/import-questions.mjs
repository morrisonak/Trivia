#!/usr/bin/env node
/**
 * Import questions from The Trivia API (https://the-trivia-api.com) into a
 * SQL file for the Cloudflare D1 `questions` table.
 *
 * Usage:
 *   node scripts/import-questions.mjs [count] [outfile]
 *   npx wrangler d1 execute trivia-db --remote --file=drizzle/import-questions.sql
 *
 * Defaults: 500 questions -> drizzle/import-questions.sql
 *
 * The generated INSERTs are guarded with WHERE NOT EXISTS on question text,
 * so re-running the file (or re-importing overlapping batches) never creates
 * duplicates.
 */

const TARGET = Math.min(parseInt(process.argv[2] ?? '500', 10) || 500, 2000)
const OUTFILE = process.argv[3] ?? 'drizzle/import-questions.sql'
const API = 'https://the-trivia-api.com/v2/questions'
const BATCH = 50 // API maximum per request
const MAX_REQUESTS = Math.ceil(TARGET / BATCH) * 3 // headroom for duplicates

const DIFFICULTY = { easy: 1, medium: 2, hard: 3 }

// "film_and_tv" -> "Film and TV"
function prettyCategory(slug) {
  return slug
    .split('_')
    .map((w) => (w === 'and' ? 'and' : w === 'tv' ? 'TV' : w[0].toUpperCase() + w.slice(1)))
    .join(' ')
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

const seen = new Set() // API question ids
const byText = new Set() // guard against same text under different ids
const rows = []
let requests = 0

while (rows.length < TARGET && requests < MAX_REQUESTS) {
  requests++
  const res = await fetch(`${API}?limit=${BATCH}&types=text_choice`)
  if (!res.ok) {
    console.error(`Request ${requests} failed: HTTP ${res.status}`)
    await new Promise((r) => setTimeout(r, 2000))
    continue
  }
  const questions = await res.json()

  for (const q of questions) {
    if (rows.length >= TARGET) break
    if (seen.has(q.id)) continue
    seen.add(q.id)

    const text = q.question?.text?.trim()
    const correct = q.correctAnswer?.trim()
    const incorrect = (q.incorrectAnswers ?? []).map((a) => String(a).trim())
    if (!text || !correct || incorrect.length !== 3) continue
    if (byText.has(text)) continue
    byText.add(text)

    const options = shuffle([correct, ...incorrect])
    const letter = ['A', 'B', 'C', 'D'][options.indexOf(correct)]

    rows.push({
      text,
      optionA: options[0],
      optionB: options[1],
      optionC: options[2],
      optionD: options[3],
      correctAnswer: letter,
      category: prettyCategory(q.category ?? 'general_knowledge'),
      difficulty: DIFFICULTY[q.difficulty] ?? 2,
    })
  }

  process.stderr.write(`\rFetched ${rows.length}/${TARGET} unique questions (${requests} requests)`)
  await new Promise((r) => setTimeout(r, 300))
}
console.error()

if (rows.length < TARGET) {
  console.error(`Warning: only collected ${rows.length} unique questions`)
}

const statements = rows.map((r) =>
  `INSERT INTO questions (text, option_a, option_b, option_c, option_d, correct_answer, category, difficulty, commentary)\n` +
  `SELECT ${sqlString(r.text)}, ${sqlString(r.optionA)}, ${sqlString(r.optionB)}, ${sqlString(r.optionC)}, ${sqlString(r.optionD)}, ` +
  `${sqlString(r.correctAnswer)}, ${sqlString(r.category)}, ${r.difficulty}, NULL\n` +
  `WHERE NOT EXISTS (SELECT 1 FROM questions WHERE text = ${sqlString(r.text)});`
)

const header =
  `-- Generated by scripts/import-questions.mjs on ${new Date().toISOString()}\n` +
  `-- Source: The Trivia API (https://the-trivia-api.com)\n` +
  `-- ${rows.length} questions; inserts are idempotent (guarded by question text)\n\n`

const { writeFileSync } = await import('node:fs')
writeFileSync(OUTFILE, header + statements.join('\n\n') + '\n')
console.error(`Wrote ${rows.length} guarded INSERTs to ${OUTFILE}`)
